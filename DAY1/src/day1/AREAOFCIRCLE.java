public class AREAOFCIRCLE {
	    void area() {
	        double r = 5;
	        double a = Math.PI * r * r;

	        System.out.println("Area of Circle = " + a);
	    }

	    public static void main(String[] args) {
	    	AREAOFCIRCLE d = new AREAOFCIRCLE();
	        d.area();
	    }
	}

